/* 1. THEME CONTROLLER */
function initTheme() {
  const savedTheme = localStorage.getItem('radpys_doc_theme') || 'dark';
  setTheme(savedTheme, false);
}

function setTheme(theme, save = true) {
  document.documentElement.setAttribute('data-theme', theme);
  const moonIcon = document.querySelector('#themeToggleBtn .icon-moon');
  const sunIcon = document.querySelector('#themeToggleBtn .icon-sun');
  
  if (theme === 'light') {
    if (moonIcon) moonIcon.style.display = 'none';
    if (sunIcon) sunIcon.style.display = 'block';
  } else {
    if (moonIcon) moonIcon.style.display = 'block';
    if (sunIcon) sunIcon.style.display = 'none';
  }

  if (save) {
    localStorage.setItem('radpys_doc_theme', theme);
  }

  renderMermaid(theme);
}

document.getElementById('themeToggleBtn')?.addEventListener('click', () => {
  const current = document.documentElement.getAttribute('data-theme') || 'dark';
  setTheme(current === 'dark' ? 'light' : 'dark', true);
});

/* 2. RIGHT TOC GENERATOR & SCROLLSPY */
function buildRightToc() {
  const rightTocNav = document.getElementById('rightTocNav');
  if (!rightTocNav) return;
  rightTocNav.innerHTML = '';

  const headers = document.querySelectorAll('.sl-content h2, .sl-content h3');
  const usedIds = new Set();
  document.querySelectorAll('[id]').forEach(el => usedIds.add(el.id));

  headers.forEach(h => {
    if (!h.id) {
      let slug = h.textContent.toLowerCase()
        .replace(/ç/g,'c').replace(/ğ/g,'g').replace(/ı/g,'i').replace(/ö/g,'o')
        .replace(/ş/g,'s').replace(/ü/g,'u')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)/g, '');
      if (!slug) slug = 'sec';
      let id = slug, n = 2;
      while (usedIds.has(id)) { id = slug + '-' + n; n++; }
      usedIds.add(id);
      h.id = id;
    }

    const li = document.createElement('li');
    li.className = 'toc-item';
    const a = document.createElement('a');
    a.href = '#' + h.id;
    a.className = h.tagName === 'H2' ? 'toc-link' : 'toc-link toc-sublink';
    a.textContent = h.textContent;
    li.appendChild(a);
    rightTocNav.appendChild(li);
  });

  attachScrollspy();
}

function attachScrollspy() {
  const tocLinks = document.querySelectorAll('.sl-right-toc .toc-link');
  const headers = document.querySelectorAll('.sl-content h2, .sl-content h3');
  const targets = Array.from(headers).filter(h => !!h.id);

  let scrollTimer = null;
  window.addEventListener('scroll', () => {
    clearTimeout(scrollTimer);
    scrollTimer = setTimeout(() => {
      let currentTarget = null;
      const scrollPos = window.scrollY + 130;

      for (let i = 0; i < targets.length; i++) {
        const t = targets[i];
        if (t.offsetTop <= scrollPos) {
          currentTarget = t;
        } else {
          break;
        }
      }

      if (currentTarget) {
        const id = currentTarget.id;
        tocLinks.forEach(a => {
          a.classList.toggle('active', a.getAttribute('href') === '#' + id);
        });
      }
    }, 80);
  }, { passive: true });
}

/* 3. GLOBAL QUICK SEARCH (Ctrl + K) */
const searchModal = document.getElementById('searchModal');
const modalSearchInput = document.getElementById('modalSearchInput');
const searchResults = document.getElementById('searchResults');
const searchTrigger = document.getElementById('searchTrigger');

function openSearchModal() {
  if (!searchModal) return;
  searchModal.classList.add('open');
  modalSearchInput.value = '';
  modalSearchInput.focus();
  renderSearchResults('');
}

function closeSearchModal() {
  if (!searchModal) return;
  searchModal.classList.remove('open');
}

searchTrigger?.addEventListener('click', openSearchModal);

document.addEventListener('keydown', (e) => {
  if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'k') {
    e.preventDefault();
    if (searchModal?.classList.contains('open')) {
      closeSearchModal();
    } else {
      openSearchModal();
    }
  } else if (e.key === 'Escape' && searchModal?.classList.contains('open')) {
    closeSearchModal();
  }
});

searchModal?.addEventListener('click', (e) => {
  if (e.target === searchModal) {
    closeSearchModal();
  }
});

modalSearchInput?.addEventListener('input', (e) => {
  renderSearchResults(e.target.value.trim().toLowerCase());
});

function renderSearchResults(query) {
  if (!searchResults) return;
  if (!query) {
    searchResults.innerHTML = `
      <div style="padding: 2rem; text-align: center; color: var(--sl-color-text-faint); font-size: 0.9rem;">
        Aramak istediğiniz terimi yazmaya başlayın...
      </div>`;
    return;
  }

  const matched = [];
  SEARCH_INDEX.forEach(item => {
    if (item.title.toLowerCase().includes(query) || (item.desc && item.desc.toLowerCase().includes(query))) {
      matched.push(item);
    }
  });

  if (matched.length === 0) {
    searchResults.innerHTML = `
      <div style="padding: 2rem; text-align: center; color: var(--sl-color-text-faint); font-size: 0.9rem;">
        "<strong>${query}</strong>" ile eşleşen sonuç bulunamadı.
      </div>`;
    return;
  }

  searchResults.innerHTML = matched.slice(0, 15).map(m => `
    <a href="${m.url}" class="search-result-item" onclick="closeSearchModal()">
      <div class="search-result-title">${m.title}</div>
      <div class="search-result-path">${m.path}</div>
    </a>
  `).join('');
}

